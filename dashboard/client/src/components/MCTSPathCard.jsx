export default function MCTSPathCard({ steps }) {
  if (!steps || steps.length === 0) return (
    <p className="text-gray-500 text-sm">No MCTS path available.</p>
  )

  return (
    <div className="space-y-3">
      {steps.map((step, idx) => (
        <div
          key={step.step}
          className={`flex items-start gap-4 p-4 rounded-xl border transition-all ${
            idx === 0
              ? 'border-indigo-600 bg-indigo-900/20'
              : 'border-gray-700 bg-gray-800/50'
          }`}
        >
          {/* Step number */}
          <div className={`shrink-0 w-8 h-8 rounded-full flex items-center justify-center text-sm font-bold ${
            idx === 0 ? 'bg-indigo-600 text-white' : 'bg-gray-700 text-gray-400'
          }`}>
            {step.step}
          </div>

          {/* Content */}
          <div className="flex-1 min-w-0">
            <div className="flex items-center justify-between gap-2">
              <p className="font-semibold text-white truncate">{step.skill_name}</p>
              {idx === 0 && (
                <span className="shrink-0 text-xs bg-indigo-700 text-indigo-200 px-2 py-0.5 rounded-full">
                  Next Up
                </span>
              )}
            </div>
            <p className="text-xs text-gray-500 mt-0.5">Problem #{step.problem_id}</p>

            {/* Mini affect indicators */}
            <div className="flex gap-3 mt-2 text-xs text-gray-400">
              <span>
                Mastery{' '}
                <span className={`font-semibold ${
                  step.predicted_correctness >= 0.8 ? 'text-emerald-400' :
                  step.predicted_correctness >= 0.6 ? 'text-yellow-400'  : 'text-red-400'
                }`}>
                  {(step.predicted_correctness * 100).toFixed(0)}%
                </span>
              </span>
              <span className="text-gray-600">|</span>
              <span>
                Frustration{' '}
                <span className={`font-semibold ${
                  step.predicted_frustration > 0.6 ? 'text-red-400' :
                  step.predicted_frustration > 0.4 ? 'text-yellow-400' : 'text-emerald-400'
                }`}>
                  {(step.predicted_frustration * 100).toFixed(0)}%
                </span>
              </span>
              <span className="text-gray-600">|</span>
              <span>
                Reward{' '}
                <span className="font-semibold text-indigo-400">
                  {step.immediate_reward.toFixed(2)}
                </span>
              </span>
            </div>
          </div>
        </div>
      ))}

      <p className="text-xs text-gray-600 pt-1">
        Path generated by Monte Carlo Tree Search over {steps.length} steps.
      </p>
    </div>
  )
}
